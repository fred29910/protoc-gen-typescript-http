func Test_messageGenerator_oneofScalarFields(t *testing.T) {
	t.Parallel()
	fd := &descriptorpb.FileDescriptorProto{
		Name:    strPtr("snap/oneof.proto"),
		Package: strPtr("snap"),
		MessageType: []*descriptorpb.DescriptorProto{
			{
				Name: strPtr("Shape"),
				OneofDecl: []*descriptorpb.OneofDescriptorProto{
					{Name: strPtr("kind")},
				},
				Field: []*descriptorpb.FieldDescriptorProto{
					{Name: strPtr("radius"), Number: int32Ptr(1), Type: fieldType(descriptorpb.FieldDescriptorProto_TYPE_FLOAT), JsonName: strPtr("radius"), OneofIndex: int32Ptr(0)},
					{Name: strPtr("side"), Number: int32Ptr(2), Type: fieldType(descriptorpb.FieldDescriptorProto_TYPE_FLOAT), JsonName: strPtr("side"), OneofIndex: int32Ptr(0)},
				},
			},
		},
	}
	f := newFileDescriptor(t, fd)
	msg := f.Messages().Get(0)
	var buf codegen.File
	buf.P("// Code generated by protoc-gen-typescript-http. DO NOT EDIT.")
	buf.P("/* eslint-disable camelcase */")
	buf.P("const encode = (s: string) => encodeURIComponent(s);")
	buf.P()
	gen := messageGenerator{pkg: f.Package(), message: msg}
	gen.Generate(&buf)
	got := string(buf.Content())

	// Should generate a discriminated union, not a flat struct.
	assert.Assert(t, strings.Contains(got, "export type Shape ="), "expected union type, got:\n%s", got)
	assert.Assert(t, strings.Contains(got, "$case: \"radius\""), "expected radius $case, got:\n%s", got)
	assert.Assert(t, strings.Contains(got, "radius: number"), "expected radius field, got:\n%s", got)
	assert.Assert(t, strings.Contains(got, "$case: \"side\""), "expected side $case, got:\n%s", got)
	assert.Assert(t, strings.Contains(got, "side: number"), "expected side field, got:\n%s", got)
	// Should NOT generate a flat struct.
	assert.Assert(t, !strings.Contains(got, "export type Shape = {"), "expected union instead of struct, got:\n%s", got)
}

