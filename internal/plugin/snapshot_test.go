// packageSnapshot builds a single-file descriptor with one message and one
// enum, then runs packageGenerator, returning the index.ts content.
func packageSnapshot(t *testing.T) string {
	t.Helper()
	fd := &descriptorpb.FileDescriptorProto{
		Name:    strPtr("snap/pkg.proto"),
		Package: strPtr("snap"),
		MessageType: []*descriptorpb.DescriptorProto{
			{
				Name: strPtr("Item"),
				Field: []*descriptorpb.FieldDescriptorProto{
					{Name: strPtr("id"), Number: int32Ptr(1), Type: fieldType(descriptorpb.FieldDescriptorProto_TYPE_INT32), JsonName: strPtr("id")},
				},
			},
		},
		EnumType: []*descriptorpb.EnumDescriptorProto{
			{
				Name: strPtr("Status"),
				Value: []*descriptorpb.EnumValueDescriptorProto{
					{Name: strPtr("UNKNOWN"), Number: int32Ptr(0)},
					{Name: strPtr("ACTIVE"), Number: int32Ptr(1)},
				},
			},
		},
	}
	f := newFileDescriptor(t, fd)
	var buf codegen.File
	gen := packageGenerator{pkg: f.Package(), files: []protoreflect.FileDescriptor{f}}
	err := gen.Generate(&buf)
	assert.NilError(t, err)
	return string(buf.Content())
}

func boolPtr(b bool) *bool {
	v := b
	return &v
}

func fieldLabel(l descriptorpb.FieldDescriptorProto_Label) *descriptorpb.FieldDescriptorProto_Label {
	v := l
	return &v
}

