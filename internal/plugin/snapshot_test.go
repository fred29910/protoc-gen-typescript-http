// newFileDescriptor is a thin wrapper around protodesc.NewFile that panics on
// error so test authors can focus on the shape of the input.
func newFileDescriptor(t *testing.T, fd *descriptorpb.FileDescriptorProto) protoreflect.FileDescriptor {
	t.Helper()
	f, err := protodesc.NewFile(fd, nil)
	assert.NilError(t, err)
	return f
}

// messageSnapshot builds a single-file descriptor with one message that has
// the supplied fields, then runs messageGenerator and returns the output.
func messageSnapshot(t *testing.T, fields []*descriptorpb.FieldDescriptorProto) string {
	t.Helper()
	fd := &descriptorpb.FileDescriptorProto{
		Name:    strPtr("snap/test.proto"),
		Package: strPtr("snap"),
		MessageType: []*descriptorpb.DescriptorProto{
			{
				Name:  strPtr("TestMessage"),
				Field: fields,
			},
		},
	}
	f := newFileDescriptor(t, fd)
	msg := f.Messages().Get(0)
	var buf codegen.File
	buf.P("// Code generated by protoc-gen-typescript-http. DO NOT EDIT.")
	buf.P("/* eslint-disable camelcase */")
	buf.P("const encode = (s: string) => encodeURIComponent(s);")
	buf.P()
	gen := messageGenerator{pkg: f.Package(), message: msg}
	gen.Generate(&buf)
	return string(buf.Content())
}

