func Test_messageGenerator_scalarFields(t *testing.T) {
	t.Parallel()
	got := messageSnapshot(t, []*descriptorpb.FieldDescriptorProto{
		{Name: strPtr("name"), Number: int32Ptr(1), Type: fieldType(descriptorpb.FieldDescriptorProto_TYPE_STRING), JsonName: strPtr("name")},
		{Name: strPtr("age"), Number: int32Ptr(2), Type: fieldType(descriptorpb.FieldDescriptorProto_TYPE_INT32), JsonName: strPtr("age")},
		{Name: strPtr("active"), Number: int32Ptr(3), Type: fieldType(descriptorpb.FieldDescriptorProto_TYPE_BOOL), JsonName: strPtr("active")},
	})

	assert.Assert(t, strings.Contains(got, "export type TestMessage = {"), "expected type declaration, got:\n%s", got)
	assert.Assert(t, strings.Contains(got, "name?: string;"), "expected string field, got:\n%s", got)
	assert.Assert(t, strings.Contains(got, "age?: number;"), "expected number field, got:\n%s", got)
	assert.Assert(t, strings.Contains(got, "active?: boolean;"), "expected boolean field, got:\n%s", got)
}

